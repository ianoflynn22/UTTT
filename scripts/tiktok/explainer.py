#!/usr/bin/env python3
"""Render the narrated explainer videos from scripts/tiktok/explainers.json.

Usage: python3 scripts/tiktok/explainer.py [out_dir] [video_id ...]
Needs: pillow, edge-tts, ffmpeg. Posts each video to Discord when DISCORD_WEBHOOK_URL is set.
Storyboards are generated by the real game engine: bun scripts/tiktok/explainers.ts > scripts/tiktok/explainers.json
"""
import asyncio, json, os, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import (W, H, FPS, FG, MUTED, GOLD, DARK_GOLD, new_frame, text_block, banner, draw_board,
                    draw_arrow, ffmpeg_writer, post_to_discord, font)

VOICE = "en-US-AndrewMultilingualNeural"  # energetic
RATE, PITCH = "+15%", "+4Hz"
MODE_LABEL = {"ultimate": "ULTIMATE TIC-TAC-TOE", "tttplus": "TIC-TAC-TOE+", "ultimateplus": "ULTIMATE TIC-TAC-TOE+"}


async def tts(text, path):
    import edge_tts
    text = text.replace("+", " plus")
    for attempt in range(4):  # the voice service occasionally drops a request
        try:
            await edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH).save(path)
            return
        except Exception as e:
            print("voice retry", attempt + 1, e)
            await asyncio.sleep(2 * (attempt + 1))
    raise SystemExit(f"Voiceover failed for: {text}")


def duration(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path])
    return float(out.strip())


def draw(video, fr, t=1.0, pulse=0.0):
    img, d = new_frame()
    d.text((W / 2, 90), "UTTT+", font=font(64), fill=GOLD, anchor="ma")
    d.text((W / 2, 170), MODE_LABEL.get(video["mode"], ""), font=font(30, False), fill=MUTED, anchor="ma")
    size = 96 + int(10 * pulse) if fr.get("stamp") else 96
    y = text_block(d, W / 2, 240, fr["title"], W - 120, size, GOLD if fr.get("stamp") else FG, max_lines=2)
    if fr.get("sub"):
        text_block(d, W / 2, y + 10, fr["sub"], W - 140, 50, FG, bold=False, max_lines=2)
    g = draw_board(d, fr["state"], last=fr.get("last"), flash=bool(fr.get("stamp")) and pulse > 0.5,
                   glow=tuple(fr.get("glow") or ()), free=bool(fr.get("free")), locked=fr.get("locked"), t=t)
    if fr.get("arrow"):
        a = fr["arrow"]
        draw_arrow(d, g, a["b"], a["c"], a["to"], t=t)
    if fr.get("banner"):
        url = "utttplus" in fr["banner"]
        banner(d, fr["banner"], "Free · Link in bio" if url else None, fill=DARK_GOLD if url else (200, 60, 50))
    return img.tobytes()


def render(video, out, tmp):
    clips = []
    for i, sc in enumerate(video["scenes"]):
        p = os.path.join(tmp, f"{video['id']}-{i}.mp3")
        asyncio.run(tts(sc["say"], p))
        clips.append((p, duration(p) + 0.25))
    lst = os.path.join(tmp, f"{video['id']}.txt")
    audio = os.path.join(tmp, f"{video['id']}.m4a")
    # Pad each line with a little silence so scenes breathe, then join.
    padded = []
    for i, (p, dur) in enumerate(clips):
        q = p.replace(".mp3", ".wav")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", p, "-af", f"apad=whole_dur={dur}",
                        "-ar", "44100", "-ac", "2", q], check=True)
        padded.append(q)
    with open(lst, "w") as f:
        f.writelines(f"file '{q}'\n" for q in padded)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c:a", "aac", audio], check=True)

    ff = ffmpeg_writer(out, audio)
    for sc, (_, dur) in zip(video["scenes"], clips):
        n = len(sc["frames"])
        per = int(dur * FPS / n)
        for k, fr in enumerate(sc["frames"]):
            frames = per if k < n - 1 else int(dur * FPS) - per * (n - 1)
            anim = int(0.5 * FPS)
            last_buf = None
            for j in range(frames):
                if j < anim:
                    ff.stdin.write(draw(video, fr, t=(j + 1) / anim, pulse=(j / anim) if fr.get("stamp") else 0))
                else:
                    last_buf = last_buf or draw(video, fr)
                    ff.stdin.write(last_buf)
    ff.stdin.close()
    if ff.wait() != 0:
        sys.exit("ffmpeg failed")


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "."
    if out_dir.endswith(".mp4"):  # old workflow passes a file name
        out_dir = os.path.dirname(out_dir) or "."
    only = set(sys.argv[2:])
    data = json.load(open(os.path.join(here, "explainers.json")))
    with tempfile.TemporaryDirectory() as tmp:
        for v in data["videos"]:
            if only and v["id"] not in only:
                continue
            out = os.path.join(out_dir, f"explainer-{v['id']}.mp4")
            render(v, out, tmp)
            print("Rendered", out, os.path.getsize(out) // 1024, "KB")
            post_to_discord(out, f"🎬 Explainer: {v['title']}\n\nCaption:\n{v['caption']}")
